/*
    RaceDay - Part 1 Section C
    SQL Server database schema and seed data

    The schema in this file matches docs/raceday.dbml.
    Run this script in SQL Server Management Studio (SSMS) on a clean SQL Server instance.
*/

IF DB_ID(N'RaceDay') IS NOT NULL
BEGIN
    ALTER DATABASE RaceDay SET SINGLE_USER WITH ROLLBACK IMMEDIATE;
    DROP DATABASE RaceDay;
END
GO

CREATE DATABASE RaceDay;
GO

USE RaceDay;
GO

/* =========================
   TABLES
   ========================= */

CREATE TABLE dbo.Users
(
    UserId INT IDENTITY(1,1) NOT NULL,
    FullName NVARCHAR(100) NOT NULL,
    Email NVARCHAR(255) NOT NULL,
    PasswordHash NVARCHAR(255) NOT NULL,
    Role NVARCHAR(20) NOT NULL
        CONSTRAINT DF_Users_Role DEFAULT (N'Participant'),
    CreatedAt DATETIME2 NOT NULL
        CONSTRAINT DF_Users_CreatedAt DEFAULT (GETDATE()),

    CONSTRAINT PK_Users PRIMARY KEY (UserId),
    CONSTRAINT UQ_Users_Email UNIQUE (Email),
    CONSTRAINT CK_Users_Role CHECK (Role IN (N'Organiser', N'Participant'))
);
GO

CREATE TABLE dbo.Events
(
    EventId INT IDENTITY(1,1) NOT NULL,
    Name NVARCHAR(150) NOT NULL,
    Description NVARCHAR(1000) NULL,
    Location NVARCHAR(255) NOT NULL,
    EventDate DATE NOT NULL,
    CreatedAt DATETIME2 NOT NULL
        CONSTRAINT DF_Events_CreatedAt DEFAULT (GETDATE()),

    CONSTRAINT PK_Events PRIMARY KEY (EventId)
);
GO

CREATE TABLE dbo.EventOrganisers
(
    EventId INT NOT NULL,
    UserId INT NOT NULL,

    CONSTRAINT PK_EventOrganisers PRIMARY KEY (EventId, UserId),

    CONSTRAINT FK_EventOrganisers_Event
        FOREIGN KEY (EventId)
        REFERENCES dbo.Events(EventId)
        ON DELETE CASCADE,

    CONSTRAINT FK_EventOrganisers_User
        FOREIGN KEY (UserId)
        REFERENCES dbo.Users(UserId)
);
GO

CREATE TABLE dbo.Categories
(
    CategoryId INT IDENTITY(1,1) NOT NULL,
    EventId INT NOT NULL,
    Name NVARCHAR(100) NOT NULL,
    DistanceKm DECIMAL(5,2) NOT NULL,
    MaxParticipants INT NOT NULL,

    CONSTRAINT PK_Categories PRIMARY KEY (CategoryId),

    CONSTRAINT FK_Categories_Event
        FOREIGN KEY (EventId)
        REFERENCES dbo.Events(EventId)
        ON DELETE CASCADE,

    CONSTRAINT UQ_Categories_Event_Name UNIQUE (EventId, Name),

    CONSTRAINT CK_Categories_Distance
        CHECK (DistanceKm > 0),

    CONSTRAINT CK_Categories_MaxParticipants
        CHECK (MaxParticipants > 0)
);
GO

CREATE TABLE dbo.Enrolments
(
    EnrolmentId INT IDENTITY(1,1) NOT NULL,
    CategoryId INT NOT NULL,
    ParticipantId INT NOT NULL,
    EnrolmentDate DATETIME2 NOT NULL
        CONSTRAINT DF_Enrolments_EnrolmentDate DEFAULT (GETDATE()),
    EmergencyContact NVARCHAR(150) NULL,

    CONSTRAINT PK_Enrolments PRIMARY KEY (EnrolmentId),

    CONSTRAINT FK_Enrolments_Category
        FOREIGN KEY (CategoryId)
        REFERENCES dbo.Categories(CategoryId)
        ON DELETE CASCADE,

    CONSTRAINT FK_Enrolments_Participant
        FOREIGN KEY (ParticipantId)
        REFERENCES dbo.Users(UserId),

    CONSTRAINT UQ_Enrolments_Category_Participant
        UNIQUE (CategoryId, ParticipantId)
);
GO

CREATE TABLE dbo.Results
(
    ResultId INT IDENTITY(1,1) NOT NULL,
    EnrolmentId INT NOT NULL,
    FinishTime TIME NOT NULL,
    Position INT NOT NULL,

    CONSTRAINT PK_Results PRIMARY KEY (ResultId),

    CONSTRAINT FK_Results_Enrolment
        FOREIGN KEY (EnrolmentId)
        REFERENCES dbo.Enrolments(EnrolmentId)
        ON DELETE CASCADE,

    CONSTRAINT UQ_Results_Enrolment UNIQUE (EnrolmentId),

    CONSTRAINT CK_Results_Position CHECK (Position > 0)
);
GO

CREATE TABLE dbo.RefreshTokens
(
    RefreshTokenId INT IDENTITY(1,1) NOT NULL,
    UserId INT NOT NULL,
    Token NVARCHAR(500) NOT NULL,
    ExpiresAt DATETIME2 NOT NULL,
    CreatedAt DATETIME2 NOT NULL
        CONSTRAINT DF_RefreshTokens_CreatedAt DEFAULT (GETDATE()),

    CONSTRAINT PK_RefreshTokens PRIMARY KEY (RefreshTokenId),

    CONSTRAINT FK_RefreshTokens_User
        FOREIGN KEY (UserId)
        REFERENCES dbo.Users(UserId)
        ON DELETE CASCADE,

    CONSTRAINT UQ_RefreshTokens_Token UNIQUE (Token)
);
GO

