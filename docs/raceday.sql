/* =========================
   VERIFICATION QUERIES
   ========================= */

SELECT
    UserId, FullName, Email, Role
FROM dbo.Users
ORDER BY UserId;
GO

SELECT
    e.EventId,
    e.Name AS EventName,
    e.Location,
    e.EventDate,
    u.FullName AS Organiser
FROM dbo.Events e
INNER JOIN dbo.EventOrganisers eo ON eo.EventId = e.EventId
INNER JOIN dbo.Users u ON u.UserId = eo.UserId
ORDER BY e.EventId;
GO

SELECT
    c.CategoryId,
    e.Name AS EventName,
    c.Name AS CategoryName,
    c.DistanceKm,
    c.MaxParticipants
FROM dbo.Categories c
INNER JOIN dbo.Events e ON e.EventId = c.EventId
ORDER BY c.EventId, c.CategoryId;
GO

SELECT
    en.EnrolmentId,
    p.FullName AS Participant,
    e.Name AS EventName,
    c.Name AS CategoryName,
    r.FinishTime,
    r.Position
FROM dbo.Enrolments en
INNER JOIN dbo.Users p ON p.UserId = en.ParticipantId
INNER JOIN dbo.Categories c ON c.CategoryId = en.CategoryId
INNER JOIN dbo.Events e ON e.EventId = c.EventId
LEFT JOIN dbo.Results r ON r.EnrolmentId = en.EnrolmentId
ORDER BY en.EnrolmentId;
GO
